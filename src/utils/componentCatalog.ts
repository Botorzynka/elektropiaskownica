/**
 * Computes the absolute canvas position of a pin given the component's center (x, y) and rotation (0, 90, 180, 270)
 */
export function getPinAbsolutePosition(component: CircuitComponent, pinId: string): Point {
  const meta = COMPONENT_CATALOG[component.type];
  const pin = meta.pins.find((p) => p.id === pinId) || meta.pins[0];
  const rad = (component.rotation * Math.PI) / 180;
  const cos = Math.round(Math.cos(rad));
  const sin = Math.round(Math.sin(rad));
  const rx = pin.dx * cos - pin.dy * sin;
  const ry = pin.dx * sin + pin.dy * cos;
  return {
    x: component.x + rx,
    y: component.y + ry,
  };
}

export function getAllComponentPinsAbsolute(component: CircuitComponent): Array<PinDefinition & { absX: number; absY: number }> {
  const meta = COMPONENT_CATALOG[component.type];
  return meta.pins.map((pin) => {
    const pos = getPinAbsolutePosition(component, pin.id);
    return {
      ...pin,
      absX: pos.x,
      absY: pos.y,
    };
  });
}
